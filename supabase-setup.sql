-- Remover todas as políticas antigas, inclusive políticas abertas com outros nomes.
DO $$
DECLARE policy_record RECORD;
BEGIN
  FOR policy_record IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN ('profiles', 'categories', 'gifts', 'reservations', 'site_settings')
  LOOP
    EXECUTE format('DROP POLICY %I ON %I.%I',
      policy_record.policyname, policy_record.schemaname, policy_record.tablename);
  END LOOP;
END $$;

REVOKE ALL ON public.profiles, public.categories, public.gifts, public.reservations, public.site_settings FROM anon, authenticated;
