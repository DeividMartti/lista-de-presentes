-- 1. Tabela de Perfil do Administrador Centralizado (profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id TEXT PRIMARY KEY DEFAULT 'admin',
  username TEXT UNIQUE NOT NULL DEFAULT 'admin',
  name TEXT NOT NULL DEFAULT 'Administrador',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 2. Tabela de Categorias
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Tabela de Presentes (gifts)
CREATE TABLE IF NOT EXISTS public.gifts (
  id TEXT PRIMARY KEY,
  user_id TEXT DEFAULT 'admin',
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT,
  image_url TEXT,
  reserved BOOLEAN DEFAULT false,
  is_reserved BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 4. Tabela de Reservas (reservations)
CREATE TABLE IF NOT EXISTS public.reservations (
  id TEXT PRIMARY KEY,
  user_id TEXT DEFAULT 'admin',
  gift_id TEXT NOT NULL REFERENCES public.gifts(id) ON DELETE CASCADE,
  guest_name TEXT NOT NULL,
  guest_whatsapp TEXT NOT NULL,
  message TEXT,
  status TEXT DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  cancelled_at TIMESTAMPTZ
);

-- 5. Tabela de Configurações do Evento (site_settings)
CREATE TABLE IF NOT EXISTS public.site_settings (
  id INT PRIMARY KEY DEFAULT 1,
  user_id TEXT DEFAULT 'admin',
  site_title TEXT NOT NULL DEFAULT 'Nosso Novo Lar',
  hero_title TEXT NOT NULL DEFAULT 'Vamos construir esse novo capítulo juntos? 💚',
  hero_description TEXT NOT NULL DEFAULT 'Estamos começando uma nova etapa e montando nosso cantinho com muito carinho.',
  hero_image_url TEXT NOT NULL DEFAULT './imagens/imagem-da-capa.png',
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- ----------------------------------------------------------------------------
-- COMPATIBILIDADE AUTOMÁTICA (Remove restrições antigas de user_id NOT NULL)
-- Corrige o erro 23502 (null value in column "user_id") caso tabelas já existam
-- ----------------------------------------------------------------------------
DO $$
DECLARE
  fk_record RECORD;
BEGIN
  -- Se houver foreign key na coluna user_id de site_settings, remove para não dar erro se referenciar tabela antiga (como app_users)
  FOR fk_record IN (
    SELECT tc.constraint_name
    FROM information_schema.table_constraints AS tc
    JOIN information_schema.key_column_usage AS kcu
      ON tc.constraint_name = kcu.constraint_name
      AND tc.table_schema = kcu.table_schema
    WHERE tc.constraint_type = 'FOREIGN KEY'
      AND tc.table_name = 'site_settings'
      AND kcu.column_name = 'user_id'
  ) LOOP
    EXECUTE 'ALTER TABLE public.site_settings DROP CONSTRAINT IF EXISTS ' || quote_ident(fk_record.constraint_name);
  END LOOP;

  -- 1. Se site_settings já existia com NOT NULL na coluna user_id, remove a restrição e seta default
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' AND table_name = 'site_settings' AND column_name = 'user_id'
  ) THEN
    ALTER TABLE public.site_settings ALTER COLUMN user_id DROP NOT NULL;
    ALTER TABLE public.site_settings ALTER COLUMN user_id SET DEFAULT 'admin';
    UPDATE public.site_settings SET user_id = 'admin' WHERE user_id IS NULL;
  ELSE
    ALTER TABLE public.site_settings ADD COLUMN IF NOT EXISTS user_id TEXT DEFAULT 'admin';
  END IF;

  -- 2. Se gifts já existia com user_id NOT NULL, remove a restrição e garante colunas reserved / is_reserved
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' AND table_name = 'gifts' AND column_name = 'user_id'
  ) THEN
    ALTER TABLE public.gifts ALTER COLUMN user_id DROP NOT NULL;
    ALTER TABLE public.gifts ALTER COLUMN user_id SET DEFAULT 'admin';
    UPDATE public.gifts SET user_id = 'admin' WHERE user_id IS NULL;
  ELSE
    ALTER TABLE public.gifts ADD COLUMN IF NOT EXISTS user_id TEXT DEFAULT 'admin';
  END IF;

  ALTER TABLE public.gifts ADD COLUMN IF NOT EXISTS reserved BOOLEAN DEFAULT false;
  ALTER TABLE public.gifts ADD COLUMN IF NOT EXISTS is_reserved BOOLEAN DEFAULT false;

  -- 3. Se reservations já existia com user_id NOT NULL, remove a restrição
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' AND table_name = 'reservations' AND column_name = 'user_id'
  ) THEN
    ALTER TABLE public.reservations ALTER COLUMN user_id DROP NOT NULL;
    ALTER TABLE public.reservations ALTER COLUMN user_id SET DEFAULT 'admin';
    UPDATE public.reservations SET user_id = 'admin' WHERE user_id IS NULL;
  ELSE
    ALTER TABLE public.reservations ADD COLUMN IF NOT EXISTS user_id TEXT DEFAULT 'admin';
  END IF;
END $$;

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles DROP COLUMN IF EXISTS password;

-- Remover todas as políticas antigas, inclusive políticas abertas com outros nomes.
DO $$
DECLARE policy_record RECORD;
BEGIN
  FOR policy_record IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN ('profiles', 'categories', 'gifts', 'reservations', 'site_settings')
  LOOP
    EXECUTE format('DROP POLICY %I ON %I.%I',
      policy_record.policyname, policy_record.schemaname, policy_record.tablename);
  END LOOP;
END $$;

REVOKE ALL ON public.profiles, public.categories, public.gifts, public.reservations, public.site_settings FROM anon, authenticated;
GRANT SELECT ON public.categories, public.gifts, public.site_settings TO anon, authenticated;
GRANT INSERT ON public.reservations TO anon;

CREATE POLICY public_read_categories ON public.categories FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY public_read_gifts ON public.gifts FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY public_read_site_settings ON public.site_settings FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY guest_create_reservation ON public.reservations FOR INSERT TO anon
  WITH CHECK (
    status = 'active'
    AND length(trim(guest_name)) BETWEEN 1 AND 120
    AND length(trim(guest_whatsapp)) BETWEEN 5 AND 30
    AND EXISTS (SELECT 1 FROM public.gifts WHERE gifts.id = reservations.gift_id)
  );

