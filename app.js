/* --------------------------------------------------------------------------
   GERENCIADOR DE DADOS E PERSISTÊNCIA (CENTRALIZADO VIA TABELA 'profiles')
   -------------------------------------------------------------------------- */
function apiFetch(url, options = {}) {
  const headers = new Headers(options.headers || {});
  const token = sessionStorage.getItem("LP_ADMIN_TOKEN");
  if (token) headers.set("Authorization", `Bearer ${token}`);
  return fetch(url, { ...options, headers });
}

class GerenciadorDados {
  constructor() {
    this.clienteSupabase = null;
    this.usandoModoLocal = true;
    this.url = localStorage.getItem("LP_SUPABASE_URL") || "";
    this.anonKey = localStorage.getItem("LP_SUPABASE_KEY") || "";
    this.perfilAdmin = { id: "admin", username: "", name: "Administrador" };
  }

  async iniciar() {
    // 1. Tenta carregar credenciais do servidor (se ambiente full-stack)
    await this.carregarConfiguracoesServidor();

    // 2. Se tiver URL e AnonKey, inicializa cliente Supabase
    const urlSalva = this.url || localStorage.getItem("LP_SUPABASE_URL");
    const keySalva = this.anonKey || localStorage.getItem("LP_SUPABASE_KEY");

    if (urlSalva && keySalva && window.supabase) {
      try {
        this.clienteSupabase = window.supabase.createClient(urlSalva, keySalva);
        const ok = await this.testarConexao();
        if (ok) {
          this.usandoModoLocal = false;
          this.url = urlSalva;
          this.anonKey = keySalva;
          // Auto-seed se o banco do Supabase estiver com tabelas vazias
          await this.garantirDadosIniciaisSupabase();
        } else {
          this.usandoModoLocal = true;
        }
      } catch (e) {
        console.warn("Falha ao inicializar Supabase, usando armazenamento local:", e);
        this.usandoModoLocal = true;
      }
    } else {
      this.usandoModoLocal = true;
    }

    // Inicializa fallback local
    if (!localStorage.getItem("LP_PRESENTES")) {
      localStorage.setItem("LP_PRESENTES", JSON.stringify(PRESENTES_INICIAIS));
    }
    if (!localStorage.getItem("LP_RESERVAS")) {
      localStorage.setItem("LP_RESERVAS", JSON.stringify([]));
    }
    if (!localStorage.getItem("LP_CONFIG")) {
      localStorage.setItem("LP_CONFIG", JSON.stringify(CONFIG_PADRAO));
    }
    localStorage.removeItem("LP_ADMIN_PASS");
  }

  async carregarConfiguracoesServidor() {
    try {
      const resp = await fetch("/api/config");
      if (resp.ok) {
        const dados = await resp.json();
        if (dados.success) {
          if (dados.supabase && dados.supabase.url && dados.supabase.anonKey) {
            this.url = dados.supabase.url;
            this.anonKey = dados.supabase.anonKey;
            localStorage.setItem("LP_SUPABASE_URL", this.url);
            localStorage.setItem("LP_SUPABASE_KEY", this.anonKey);
          }
          if (dados.siteSettings && dados.siteSettings.nome_evento) {
            localStorage.setItem("LP_CONFIG", JSON.stringify(dados.siteSettings));
          }
          if (dados.users && dados.users[0]) {
            this.perfilAdmin = dados.users[0];
            localStorage.setItem("LP_ADMIN_USER", dados.users[0].username);
          }
        }
      }
    } catch (e) {
      // Ambiente estático como GitHub Pages
    }
  }

  obterUrl() {
    return this.url || localStorage.getItem("LP_SUPABASE_URL") || "";
  }

  obterKey() {
    return this.anonKey || localStorage.getItem("LP_SUPABASE_KEY") || "";
  }

  async definirCredenciais(url, key) {
    this.url = (url || "").trim();
    this.anonKey = (key || "").trim();
    localStorage.setItem("LP_SUPABASE_URL", this.url);
    localStorage.setItem("LP_SUPABASE_KEY", this.anonKey);

    if (this.url && this.anonKey && window.supabase) {
      try {
        this.clienteSupabase = window.supabase.createClient(this.url, this.anonKey);
        const ok = await this.testarConexao();
        this.usandoModoLocal = !ok;
        if (ok) {
          await this.garantirDadosIniciaisSupabase();
        }
      } catch (e) {
        this.usandoModoLocal = true;
      }
    } else {
      this.clienteSupabase = null;
      this.usandoModoLocal = true;
    }
  }

  async testarConexao() {
    if (!this.clienteSupabase) return false;
    try {
      // Confirma que a leitura pública das categorias está disponível.
      const { error: catErr } = await this.clienteSupabase.from("categories").select("count", { count: "exact", head: true });
      return !catErr;
    } catch (e) {
      return false;
    }
  }

  async garantirDadosIniciaisSupabase() {
    if (!this.clienteSupabase) return;
    try {
      // Garante configurações iniciais do site
      const { data: sData } = await this.clienteSupabase.from("site_settings").select("id").eq("id", 1).maybeSingle();
      if (!sData) {
        await this.clienteSupabase.from("site_settings").insert({
          id: 1,
          user_id: "admin",
          site_title: CONFIG_PADRAO.nome_evento,
          hero_title: CONFIG_PADRAO.hero_titulo,
          hero_description: CONFIG_PADRAO.hero_descricao,
          hero_image_url: CONFIG_PADRAO.hero_imagem
        });
      }

      // Se a tabela de presentes estiver vazia, popula com os presentes iniciais
      const { count } = await this.clienteSupabase.from("gifts").select("*", { count: "exact", head: true });
      if (count === 0) {
        const paraInserir = PRESENTES_INICIAIS.map(p => ({
          id: p.id,
          user_id: "admin",
          title: p.nome,
          category: p.categoria,
          description: p.descricao || "",
          image_url: p.imagem || "",
          reserved: false,
          is_reserved: false
        }));
        await this.clienteSupabase.from("gifts").insert(paraInserir);
      }
    } catch (e) {
      console.warn("Aviso ao verificar dados iniciais do Supabase:", e);
    }
  }

  // --- AUTENTICAÇÃO COM A TABELA 'profiles' ---
  async autenticarAdmin(username, password) {
    const cleanUser = (username || "").trim().toLowerCase();
    const cleanPass = (password || "").trim();

    if (!cleanUser || !cleanPass) {
      return { sucesso: false, mensagem: "Informe o usuário e a senha." };
    }

    // O login administrativo só é validado pelo servidor.
    try {
      const resp = await fetch("/api/admin/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ username: cleanUser, password: cleanPass })
      });
      const resJson = await resp.json();
      if (resp.ok && resJson.success) {
        this.perfilAdmin = resJson.user || { id: "admin", username: cleanUser, name: "Administrador" };
        localStorage.setItem("LP_ADMIN_USER", this.perfilAdmin.username);
        sessionStorage.setItem("LP_ADMIN_TOKEN", resJson.token);
        return { sucesso: true, perfil: this.perfilAdmin };
      } else {
        return { sucesso: false, mensagem: resJson.message || "Usuário ou senha incorretos." };
      }
    } catch (netErr) {
      return { sucesso: false, mensagem: "Não foi possível acessar o servidor de autenticação." };
    }
  }

  async obterPerfilAdmin() {
    const localUser = localStorage.getItem("LP_ADMIN_USER") || "";
    return { id: "admin", username: localUser, name: "Administrador" };
  }

  async salvarPerfilAdmin(dados) {
    const { name, username, newPassword } = dados;
    const cleanUser = (username || "").trim();
    const cleanName = (name || "").trim() || "Administrador";

    // Atualiza no servidor central.
    try {
      const response = await apiFetch("/api/admin/alterar-senha", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: cleanName,
          username: cleanUser,
          newPassword: newPassword || undefined
        })
      });
      const result = await response.json();
      if (!response.ok || !result.success) {
        throw new Error(result.message || "Não foi possível atualizar a conta.");
      }
    } catch (e) {
      throw e;
    }

    // 3. Atualiza localmente
    this.perfilAdmin.name = cleanName;
    this.perfilAdmin.username = cleanUser;
    localStorage.setItem("LP_ADMIN_USER", cleanUser);
    return this.perfilAdmin;
  }

  // --- CONFIGURAÇÕES DO SITE ---
  async obterConfiguracoes() {
    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        const { data, error } = await this.clienteSupabase
          .from("site_settings")
          .select("*")
          .eq("id", 1)
          .maybeSingle();

        if (!error && data) {
          return {
            nome_evento: data.site_title || CONFIG_PADRAO.nome_evento,
            hero_titulo: data.hero_title || CONFIG_PADRAO.hero_titulo,
            hero_descricao: data.hero_description || CONFIG_PADRAO.hero_descricao,
            hero_imagem: data.hero_image_url || "./imagens/imagem-da-capa.png"
          };
        }
      } catch (e) {}
    }

    const local = localStorage.getItem("LP_CONFIG");
    return local ? JSON.parse(local) : CONFIG_PADRAO;
  }

  async salvarConfiguracoes(cfg) {
    localStorage.setItem("LP_CONFIG", JSON.stringify(cfg));

    try {
      await apiFetch("/api/config/site", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(cfg)
      });
    } catch (e) {}

    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        await this.clienteSupabase.from("site_settings").upsert({
          id: 1,
          user_id: "admin",
          site_title: cfg.nome_evento,
          hero_title: cfg.hero_titulo,
          hero_description: cfg.hero_descricao,
          hero_image_url: cfg.hero_imagem,
          updated_at: new Date().toISOString()
        }, { onConflict: "id" });
      } catch (e) {}
    }
  }

  // --- PRESENTES ---
  async obterPresentes() {
    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        const { data, error } = await this.clienteSupabase
          .from("gifts")
          .select("*")
          .order("created_at", { ascending: true });

        if (!error && Array.isArray(data) && data.length > 0) {
          return data.map(g => ({
            id: String(g.id),
            nome: g.title,
            categoria: g.category,
            descricao: g.description || "",
            imagem: g.image_url || "",
            reservado: Boolean(g.reserved !== undefined ? g.reserved : g.is_reserved)
          }));
        }
      } catch (e) {}
    }

    // Servidor Express
    try {
      const resp = await apiFetch("/api/presentes");
      if (resp.ok) {
        const lista = await resp.json();
        if (Array.isArray(lista) && lista.length > 0) {
          localStorage.setItem("LP_PRESENTES", JSON.stringify(lista));
          return lista;
        }
      }
    } catch (e) {}

    // Fallback local
    const local = localStorage.getItem("LP_PRESENTES");
    return local ? JSON.parse(local) : PRESENTES_INICIAIS;
  }

  async salvarPresente(presente) {
    const todos = await this.obterPresentes();
    const id = presente.id || String(Date.now());
    const itemAtualizado = { ...presente, id };

    const idx = todos.findIndex(p => String(p.id) === String(id));
    if (idx >= 0) {
      todos[idx] = itemAtualizado;
    } else {
      todos.push(itemAtualizado);
    }
    localStorage.setItem("LP_PRESENTES", JSON.stringify(todos));

    // Servidor
    try {
      await apiFetch("/api/presentes", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(itemAtualizado)
      });
    } catch (e) {}

    // Supabase
    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        await this.clienteSupabase.from("gifts").upsert({
          id: id,
          user_id: "admin",
          title: itemAtualizado.nome,
          category: itemAtualizado.categoria,
          description: itemAtualizado.descricao || "",
          image_url: itemAtualizado.imagem || "",
          reserved: Boolean(itemAtualizado.reservado),
          is_reserved: Boolean(itemAtualizado.reservado),
          updated_at: new Date().toISOString()
        }, { onConflict: "id" });
      } catch (e) {}
    }

    return itemAtualizado;
  }

  async excluirPresente(id) {
    const todos = await this.obterPresentes();
    const filtrados = todos.filter(p => String(p.id) !== String(id));
    localStorage.setItem("LP_PRESENTES", JSON.stringify(filtrados));

    try {
      await apiFetch(`/api/presentes/${encodeURIComponent(id)}`, { method: "DELETE" });
    } catch (e) {}

    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        await this.clienteSupabase.from("gifts").delete().eq("id", String(id));
      } catch (e) {}
    }
  }

  // --- RESERVAS ---
  async obterReservas() {
    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        const { data, error } = await this.clienteSupabase
          .from("reservations")
          .select("*, gifts(title, image_url, category)")
          .order("created_at", { ascending: false });

        if (!error && Array.isArray(data)) {
          return data.map(r => ({
            id: String(r.id),
            gift_id: String(r.gift_id),
            presente_nome: r.gifts?.title || "Presente",
            presente_imagem: r.gifts?.image_url || "",
            guest_name: r.guest_name,
            guest_whatsapp: r.guest_whatsapp,
            message: r.message || "",
            status: r.status,
            created_at: r.created_at
          }));
        }
      } catch (e) {}
    }

    try {
      const resp = await apiFetch("/api/reservas");
      if (resp.ok) {
        const lista = await resp.json();
        if (Array.isArray(lista)) {
          localStorage.setItem("LP_RESERVAS", JSON.stringify(lista));
          return lista;
        }
      }
    } catch (e) {}

    const local = localStorage.getItem("LP_RESERVAS");
    return local ? JSON.parse(local) : [];
  }

  async criarReserva(giftId, guestName, guestWhatsapp, message) {
    const novaReserva = {
      id: "res_" + Date.now(),
      gift_id: String(giftId),
      guest_name: guestName.trim(),
      guest_whatsapp: guestWhatsapp.trim(),
      message: (message || "").trim(),
      status: "active",
      created_at: new Date().toISOString()
    };

    // Atualiza local
    const reservasLocais = await this.obterReservas();
    reservasLocais.unshift(novaReserva);
    localStorage.setItem("LP_RESERVAS", JSON.stringify(reservasLocais));

    // Marca presente como reservado localmente
    const presentes = await this.obterPresentes();
    const p = presentes.find(item => String(item.id) === String(giftId));
    if (p) {
      p.reservado = true;
      localStorage.setItem("LP_PRESENTES", JSON.stringify(presentes));
    }

    // Servidor
    try {
      await apiFetch("/api/reservas", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          presenteId: giftId,
          guestName: novaReserva.guest_name,
          guestWhatsapp: novaReserva.guest_whatsapp,
          mensagem: novaReserva.message
        })
      });
    } catch (e) {}

    // Supabase
    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        await this.clienteSupabase.from("reservations").insert({
          id: novaReserva.id,
          user_id: "admin",
          gift_id: String(giftId),
          guest_name: novaReserva.guest_name,
          guest_whatsapp: novaReserva.guest_whatsapp,
          message: novaReserva.message,
          status: "active"
        });
        await this.clienteSupabase.from("gifts").update({ reserved: true, is_reserved: true }).eq("id", String(giftId));
      } catch (e) {
        console.warn("Erro ao salvar reserva no Supabase:", e);
      }
    }

    return { sucesso: true, reserva: novaReserva };
  }

  async cancelarReserva(reservaId) {
    const reservas = await this.obterReservas();
    const r = reservas.find(item => String(item.id) === String(reservaId));
    if (r) {
      r.status = "cancelled";
      localStorage.setItem("LP_RESERVAS", JSON.stringify(reservas));

      const presentes = await this.obterPresentes();
      const p = presentes.find(item => String(item.id) === String(r.gift_id));
      if (p) {
        p.reservado = false;
        localStorage.setItem("LP_PRESENTES", JSON.stringify(presentes));
      }
    }

    try {
      await apiFetch(`/api/reservas/${encodeURIComponent(reservaId)}/cancelar`, { method: "POST" });
    } catch (e) {}

    if (!this.usandoModoLocal && this.clienteSupabase) {
      try {
        const { data: resv } = await this.clienteSupabase
          .from("reservations")
          .update({ status: "cancelled", cancelled_at: new Date().toISOString() })
          .eq("id", String(reservaId))
          .select("gift_id")
          .maybeSingle();

        if (resv && resv.gift_id) {
          await this.clienteSupabase.from("gifts").update({ reserved: false, is_reserved: false }).eq("id", String(resv.gift_id));
        }
      } catch (e) {}
    }
  }
}

